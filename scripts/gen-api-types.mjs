#!/usr/bin/env node

// Generate frontend/src/api/schema-types.ts from lib/contracts/*.js.
//
//   node scripts/gen-api-types.mjs            # write the file
//   node scripts/gen-api-types.mjs --check    # verify committed file is current (exit 1 on drift)
//   node scripts/gen-api-types.mjs --stdout   # print instead of writing
//
// Zero dependencies: the schema's toJSON() meta description is all this needs.
// Output is deterministic (definitions order is fixed in lib/contracts/index.js).

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = join(ROOT, 'frontend', 'src', 'api', 'schema-types.ts');

const HEADER = `// @generated by scripts/gen-api-types.mjs — do not edit
//
// Single source of truth: lib/contracts/*.js. Regenerate with \`npm run build:contract\`.
// test/contract.test.js fails when this file is out of date (drift gate).
`;

/** Parenthesize unions when they are used as an array element / record value. */
function wrap(type) {
  return type.includes(' | ') ? `(${type})` : type;
}

function tsType(meta) {
  switch (meta.kind) {
    case 'string':
      return 'string';
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'literal':
      return typeof meta.value === 'string' ? `'${meta.value.replace(/'/g, "\\'")}'` : String(meta.value);
    case 'ref':
      return meta.name;
    case 'nullable':
      return `${tsType(meta.of)} | null`;
    case 'array':
      return `${wrap(tsType(meta.of))}[]`;
    case 'record':
      return `Record<string, ${tsType(meta.of)}>`;
    case 'union':
      return meta.variants.map(tsType).join(' | ');
    case 'object':
      return inlineObject(meta);
    default:
      throw new Error(`unsupported schema kind: ${meta.kind}`);
  }
}

function inlineObject(meta) {
  const members = meta.fields.map((field) => `${field.name}${field.optional ? '?' : ''}: ${tsType(field.schema)};`);
  if (meta.open) members.push('[key: string]: unknown;');
  // Biome/tsc style: no trailing semicolon on the last member of an inline object.
  const body = members.join(' ').replace(/;$/, '');
  return `{ ${body} }`;
}

function declaration(schema) {
  const meta = schema.toJSON(true);
  const name = schema.defName;
  if (meta.kind === 'object') {
    const lines = meta.fields.map((field) => `  ${field.name}${field.optional ? '?' : ''}: ${tsType(field.schema)};`);
    if (meta.open) lines.push('  [key: string]: unknown;');
    return `export interface ${name} {\n${lines.join('\n')}\n}\n`;
  }
  return `export type ${name} = ${tsType(meta)};\n`;
}

function generate() {
  const contracts = require(join(ROOT, 'lib', 'contracts'));
  const blocks = contracts.definitions.map(declaration);
  return `${HEADER}\n${blocks.join('\n')}`;
}

function firstDiff(expected, actual) {
  const a = expected.split('\n');
  const b = actual.split('\n');
  for (let index = 0; index < Math.max(a.length, b.length); index++) {
    if (a[index] !== b[index]) {
      return `line ${index + 1}:\n  expected: ${JSON.stringify(a[index] ?? '<eof>')}\n  actual:   ${JSON.stringify(b[index] ?? '<eof>')}`;
    }
  }
  return 'files differ';
}

const args = new Set(process.argv.slice(2));
const output = generate();

if (args.has('--stdout')) {
  process.stdout.write(output);
} else if (args.has('--check')) {
  let current = '';
  try {
    current = readFileSync(TARGET, 'utf8');
  } catch {
    console.error(`gen-api-types: missing ${TARGET}; run \`npm run build:contract\``);
    process.exit(1);
  }
  if (current !== output) {
    console.error(`gen-api-types: ${TARGET} is stale — run \`npm run build:contract\`.\n${firstDiff(output, current)}`);
    process.exit(1);
  }
  console.log(`gen-api-types: ${TARGET} is up to date (${output.split('\n').length - 1} lines)`);
} else {
  writeFileSync(TARGET, output);
  console.log(`gen-api-types: wrote ${TARGET} (${output.split('\n').length - 1} lines)`);
}
