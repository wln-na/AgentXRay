// Contract-layer tests.
//
// (a) Drift gate: frontend/src/api/schema-types.ts must be byte-identical to
//     what scripts/gen-api-types.mjs generates from lib/contracts/*.js. This is
//     what stops the frontend types from silently diverging again.
// (b) Live check: a hermetic server (test/helpers) serves fixture sessions on
//     all platforms; the real responses are parsed with the same schemas the
//     codegen consumes. Also pins the additive query validation (400 naming the
//     offending parameter) without touching response shapes.

const test = require('node:test');
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const { readFileSync } = require('node:fs');
const path = require('node:path');

const { startServer, getJson } = require('./helpers');
const contracts = require('../lib/contracts');

const ROOT = path.join(__dirname, '..');
const GENERATOR = path.join(ROOT, 'scripts', 'gen-api-types.mjs');
const TARGET = path.join(ROOT, 'frontend', 'src', 'api', 'schema-types.ts');

function runGenerator(args) {
  return spawnSync(process.execPath, [GENERATOR, ...args], { encoding: 'utf8', cwd: ROOT });
}

test('generated schema-types.ts is current (drift gate)', () => {
  const run = runGenerator(['--check']);
  assert.equal(run.status, 0, `gen-api-types --check failed:\n${run.stderr || run.stdout}`);
});

test('generator output is deterministic and matches the committed file', () => {
  const first = runGenerator(['--stdout']);
  const second = runGenerator(['--stdout']);
  assert.equal(first.status, 0, first.stderr);
  assert.equal(second.status, 0, second.stderr);
  assert.equal(first.stdout, second.stdout, 'generator is not deterministic');

  const committed = readFileSync(TARGET, 'utf8');
  assert.ok(
    committed.startsWith('// @generated by scripts/gen-api-types.mjs'),
    'schema-types.ts is missing the @generated header'
  );
  assert.equal(committed, first.stdout, 'committed schema-types.ts differs from generator output');
});

test('query schemas reject values the routes used to coerce silently', () => {
  const bad = [
    [{ limit: 'abc' }, '$.limit'],
    [{ limit: '1.5' }, '$.limit'],
    [{ limit: '' }, '$.limit'],
    [{ limit: '-1' }, '$.limit'],
    [{ limit: ['1', '2'] }, '$.limit'],
    [{ before: 'nope' }, '$.before'],
    [{ agent: 'bad!name' }, '$.agent'],
    [{ include_subagents: 'yes' }, '$.include_subagents'],
    [{ refresh: 'sometimes' }, '$.refresh'],
  ];
  for (const [query, expectedPath] of bad) {
    const route = query.refresh === undefined ? 'sessions.list' : 'sessions.tasks';
    assert.throws(
      () => contracts.validateQuery(route, query),
      (error) => {
        assert.equal(error.name, 'ContractError');
        assert.ok(error.path.startsWith(expectedPath), `path ${error.path} should start with ${expectedPath}`);
        return true;
      }
    );
  }

  // Accepted spellings (0 is the existing "no limit" sentinel).
  assert.deepEqual(contracts.validateQuery('sessions.list', { limit: '0', before: '0' }), { limit: 0, before: 0 });
  assert.deepEqual(contracts.validateQuery('sessions.list', { limit: '25' }), { limit: 25 });
  assert.deepEqual(contracts.validateQuery('sessions.list', { include_subagents: '1' }), { include_subagents: true });
  assert.deepEqual(contracts.validateQuery('sessions.tasks', { refresh: 'true' }), { refresh: true });

  assert.throws(
    () => contracts.validateContextMessageIds(['ok-id', 'has space']),
    (error) => {
      assert.equal(error.name, 'ContractError');
      assert.equal(error.path, '$.messageIds[1]');
      return true;
    }
  );
  assert.doesNotThrow(() => contracts.validateContextMessageIds(['ok-id', 'uuid:1']));
});

test('response schemas reject shape drift', () => {
  const page = { total: 0, limit: 100, start: 0, end: 0, hasMoreBefore: false, nextBefore: null };
  assert.doesNotThrow(() => contracts.schemas.SessionsPage.parse({ sessions: [], page }));
  assert.throws(() => contracts.schemas.SessionsPage.parse({ sessions: [] }), /page.*is required/);
  assert.throws(
    () => contracts.schemas.SessionsPage.parse({ sessions: [{ timestamp: null }], page }),
    /\$\.sessions\[0\]\.id: is required/
  );
  assert.throws(
    () => contracts.schemas.SessionFull.parse({ session: { id: 'x' }, messages: [] }),
    /complete.*is required/
  );
});

test('live responses from a scratch server satisfy the schemas', async (t) => {
  const srv = await startServer();
  t.after(() => srv.stop());

  // --- session lists: every platform with fixture data ---
  const agents = await getJson(srv.base, '/api/agents');
  assert.ok(agents.length > 0, 'fixtures should expose at least one openclaw agent');
  const listPaths = [
    `/api/openclaw/sessions?agent=${encodeURIComponent(agents[0])}`,
    '/api/codex/sessions',
    '/api/claude-code/sessions',
    '/api/claude-desktop/sessions',
    '/api/omp/sessions',
    '/api/dsh/sessions',
    '/api/gemini/sessions',
    '/api/cursor/sessions',
    '/api/trae/sessions',
    '/api/workbuddy/sessions',
  ];
  const lists = {};
  for (const pathname of listPaths) {
    const sep = pathname.includes('?') ? '&' : '?';
    const body = await getJson(srv.base, `${pathname}${sep}limit=100`);
    contracts.routes['sessions.list'].response.parse(body);
    assert.ok(Array.isArray(body.sessions), `${pathname} must return { sessions }`);
    assert.equal(typeof body.page.hasMoreBefore, 'boolean', `${pathname} page.hasMoreBefore`);
    lists[pathname] = body;
  }

  // --- paging still works: limit=1 → one item, hasMore + cursor ---
  const paged = await getJson(srv.base, '/api/codex/sessions?limit=1');
  contracts.schemas.SessionsPage.parse(paged);
  assert.equal(paged.sessions.length, 1);
  assert.equal(paged.page.limit, 1);
  assert.equal(paged.page.hasMoreBefore, true);
  assert.equal(typeof paged.page.nextBefore, 'string');

  // --- detail / full / messages for the same session ---
  const codexSession = lists['/api/codex/sessions'].sessions[0];
  assert.ok(codexSession, 'fixture codex list must not be empty');
  const detailBase = `/api/codex/sessions/${encodeURIComponent(codexSession.id)}`;
  const detailPath = `${detailBase}?limit=60`;
  const detail = await getJson(srv.base, detailPath);
  contracts.schemas.SessionDetail.parse(detail);
  assert.ok(detail.messagePage, 'paged detail must carry messagePage');

  const full = await getJson(srv.base, `${detailBase}/full`);
  contracts.schemas.SessionFull.parse(full);
  assert.equal(full.complete, true);
  assert.equal('messagePage' in full, false, '/full must not carry messagePage');

  const messages = await getJson(srv.base, `${detailBase}/messages?limit=2`);
  contracts.schemas.SessionMessagesPage.parse(messages);
  assert.ok(messages.messages.length <= 2);

  const tasks = await getJson(srv.base, `${detailBase}/tasks`);
  contracts.schemas.SessionTaskAnalysis.parse(tasks);
  const children = await getJson(srv.base, `${detailBase}/children`);
  contracts.routes['sessions.children'].response.parse(children);

  // --- context: single + batch ---
  // The newest codex fixture session may be a metadata-only rollout, so pick a
  // session that actually has user messages to anchor on.
  let contextPath = detailBase;
  let contextDetail = detail;
  if (!contextDetail.messages.some((message) => message.role === 'user')) {
    for (const candidate of lists['/api/codex/sessions'].sessions) {
      const candidatePath = `/api/codex/sessions/${encodeURIComponent(candidate.id)}`;
      const candidateDetail = await getJson(srv.base, candidatePath);
      if (candidateDetail.messages.some((message) => message.role === 'user')) {
        contextPath = candidatePath;
        contextDetail = candidateDetail;
        break;
      }
    }
  }
  const firstUserIndex = contextDetail.messages.findIndex((message) => message.role === 'user');
  assert.ok(firstUserIndex >= 0, 'fixture session needs a user message for context tests');
  const single = await getJson(srv.base, `${contextPath}/context?messageIndex=${firstUserIndex}`);
  contracts.schemas.ContextSnapshot.parse(single);

  // Batch form: codex user messages carry no id, so anchor on unknown ids — the
  // contract is that per-id failures land in `errors` instead of failing the
  // whole batch.
  const batchIds = ['missing-anchor-a', 'missing-anchor-b'];
  const batch = await getJson(srv.base, `${contextPath}/context?messageIds=${encodeURIComponent(batchIds.join(','))}`);
  contracts.schemas.ContextBatch.parse(batch);
  assert.equal(batch.snapshots.length + batch.errors.length, batchIds.length);
  assert.equal(batch.errors.length, 2, 'unknown anchors must be reported per id');

  // --- additive query validation: 400 names the offending parameter ---
  const badRequests = [
    ['/api/codex/sessions?limit=abc', 'limit'],
    ['/api/codex/sessions?limit=-1', 'limit'],
    ['/api/codex/sessions?before=1.5', 'before'],
    [`${detailBase}?limit=abc`, 'limit'],
    [`${detailBase}?before=oops`, 'before'],
    [`${detailBase}/messages?limit=abc`, 'limit'],
    [`${contextPath}/context?agent=bad!name&messageIndex=0`, 'agent'],
    [`${contextPath}/context?messageIds=${encodeURIComponent('has space')}`, 'messageIds'],
  ];
  for (const [pathname, param] of badRequests) {
    const res = await fetch(srv.base + pathname);
    assert.equal(res.status, 400, `${pathname} should be a 400`);
    const body = await res.json();
    assert.match(body.error, new RegExp(param), `${pathname} error should name ${param}: ${body.error}`);
  }

  // Valid values are untouched (no status-code semantics changed).
  const okResponse = await fetch(`${srv.base}${detailBase}?limit=0&before=0`);
  assert.equal(okResponse.status, 200);
  contracts.schemas.SessionDetail.parse(await okResponse.json());
});
